// src/utils/errorMessages.js

export const getFriendlyErrorMessage = (errorMessage, isLogin = false) => {
  // Приводим к нижнему регистру для надёжного сравнения
  const msg = (errorMessage || '').toLowerCase();

  // Общие фразы
  if (msg.includes('заполните все поля') || msg.includes('все поля')) {
    return 'Чтобы завершить регистрацию, заполните все поля в форме.';
  }

  if (msg.includes('некоррект')) {
    return isLogin
      ? 'Введенные вами данные не распознаны. Проверьте свой логин и пароль и повторите попытку входа.'
      : 'Введенные вами данные не корректны. Чтобы завершить регистрацию, введите данные корректно и повторите попытку.';
  }

  // Стандартные ошибки API
  if (msg.includes('пользователь с таким логином уже существует')) {
    return 'Введенные вами данные не корректны. Чтобы завершить регистрацию, введите данные корректно и повторите попытку.';
  }

  if (msg.includes('неверный логин') || msg.includes('неверный пароль')) {
    return 'Введенные вами данные не распознаны. Проверьте свой логин и пароль и повторите попытку входа.';
  }

  // Любая другая ошибка — обобщённое сообщение
  return isLogin
    ? 'Введенные вами данные не распознаны. Проверьте свой логин и пароль и повторите попытку входа.'
    : 'Введенные вами данные не корректны. Чтобы завершить регистрацию, введите данные корректно и повторите попытку.';
};